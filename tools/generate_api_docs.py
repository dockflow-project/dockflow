"""Generate the checked-in API reference from the service's actual OpenAPI contract.

App construction does not enter its lifespan, open project state or start workers.
Use --check in documentation validation to detect a stale generated reference.
"""

import argparse
import json
from copy import deepcopy
from pathlib import Path

from dockflow_pipelines.config import DEFAULTS, Settings
from dockflow_pipelines.service import create_app

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "docs" / "reference"


def contract() -> dict:
    data = deepcopy(DEFAULTS)
    state = ROOT / "tmp" / "api-documentation-unused-state"
    settings = Settings(
        config_path=ROOT / "examples" / "quickstart" / ".dockflow-pipelines.toml",
        project_id="api-documentation",
        root=ROOT,
        state=state,
        work_directory=state / "work",
        definitions=data["definitions"],
        execution=data["execution"],
        images=data["images"],
        artifacts={
            **data["artifacts"],
            "root": ROOT / "tmp" / "api-documentation-artifacts",
        },
        reuse=data["reuse"],
        policies=data["policies"],
        client=data["client"],
        service=data["service"],
        sources={},
        state_storage={"backend": "sqlite", "database": ".dockflow/state.sqlite"},
        cache=data["cache"],
    )
    return create_app(settings, execute=False).openapi()


def schema_label(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return f"constant {json.dumps(schema['const'])}"
    if "enum" in schema:
        return ", ".join(json.dumps(value) for value in schema["enum"])
    kind = schema.get("type", "oneOf" if "oneOf" in schema else "object")
    if isinstance(kind, list):
        return " or ".join(kind)
    if kind == "array":
        return f"array of {schema_label(schema.get('items', {}))}"
    return kind


def markdown(document: dict) -> str:
    lines = [
        "# Generated HTTP API reference",
        "",
        "[Documentation index](../README.md) · [API guide](../api.md) · "
        "[Complete OpenAPI JSON](openapi.json)",
        "",
        "Generated by `python tools/generate_api_docs.py` from the service's actual",
        "OpenAPI contract. Do not edit this file directly. The JSON includes full",
        "request/response schemas; this page is a navigation aid, not a second contract.",
        "The KFP adapter's bounded behavior is explained in the API guide.",
        "",
        f"OpenAPI **{document['openapi']}**; application **{document['info']['version']}**.",
        "",
        "## Routes",
        "",
        "| Method | Path | Purpose | Request body |",
        "| --- | --- | --- | --- |",
    ]
    for path, methods in sorted(document["paths"].items()):
        for method, operation in sorted(methods.items()):
            if method not in {"get", "post", "put", "patch", "delete"}:
                continue
            body = operation.get("requestBody", {}).get("content", {})
            labels = [
                f"{content_type}: {schema_label(value.get('schema', {}))}"
                for content_type, value in sorted(body.items())
            ]
            summary = operation.get("summary", operation.get("operationId", ""))
            lines.append(
                f"| `{method.upper()}` | `{path}` | {summary} | "
                f"{'; '.join(labels) or '—'} |"
            )
    lines.extend(["", "## Models", ""])
    for name, schema in sorted(
        document.get("components", {}).get("schemas", {}).items()
    ):
        lines.extend([f"### {name}", ""])
        if not schema.get("properties"):
            lines.extend([f"Shape: `{schema_label(schema)}`.", ""])
            continue
        lines.extend(
            ["| Field | Type / admitted values | Required |", "| --- | --- | --- |"]
        )
        for field, value in schema["properties"].items():
            label = schema_label(value).replace("|", "\\|")
            required = "yes" if field in schema.get("required", []) else "no"
            lines.append(f"| `{field}` | {label} | {required} |")
        lines.append("")
        if schema.get("oneOf"):
            lines.extend(
                ["Additional alternative constraints are defined in OpenAPI.", ""]
            )
        if schema.get("additionalProperties") is False:
            lines.extend(["Unknown fields are not admitted.", ""])
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    document = contract()
    files = {
        "openapi.json": json.dumps(document, indent=2, sort_keys=True) + "\n",
        "api.md": markdown(document),
    }
    stale = []
    for filename, contents in files.items():
        path = DESTINATION / filename
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != contents:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents, encoding="utf-8")
    if stale:
        parser.exit(1, "Stale API documentation: " + ", ".join(stale) + "\n")
    print(
        "API documentation is current" if args.check else "Generated API documentation"
    )


if __name__ == "__main__":
    main()
